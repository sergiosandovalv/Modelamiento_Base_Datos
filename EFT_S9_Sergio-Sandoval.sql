-- PASO 5: CREACION DE TRIGGERS DEL ARCO

-- Valida que PERSONAL_PLANTA corresponda al tipo P.
CREATE OR REPLACE TRIGGER ARC_FKArc_1_PERSONAL_PLANTA
BEFORE INSERT OR UPDATE OF cod_inscripcion
ON PERSONAL_PLANTA
FOR EACH ROW
DECLARE
    d VARCHAR2(1);
BEGIN
    SELECT A.tipo_trabajador INTO d
    FROM TRABAJADOR A
    WHERE A.cod_inscripcion = :NEW.cod_inscripcion;

    IF (d IS NULL OR d <> 'P') THEN
        raise_application_error(
            -20223,
            'PERSONAL_PLANTA no corresponde al tipo de trabajador P'
        );
    END IF;

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        NULL;
    WHEN OTHERS THEN
        RAISE;
END;
/

-- Valida que JUGADOR corresponda al tipo J.
CREATE OR REPLACE TRIGGER ARC_FKArc_1_JUGADOR
BEFORE INSERT OR UPDATE OF cod_inscripcion
ON JUGADOR
FOR EACH ROW
DECLARE
    d VARCHAR2(1);
BEGIN
    SELECT A.tipo_trabajador INTO d
    FROM TRABAJADOR A
    WHERE A.cod_inscripcion = :NEW.cod_inscripcion;

    IF (d IS NULL OR d <> 'J') THEN
        raise_application_error(
            -20223,
            'JUGADOR no corresponde al tipo de trabajador J'
        );
    END IF;

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        NULL;
    WHEN OTHERS THEN
        RAISE;
END;
/


